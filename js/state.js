    // Función formal para calcular correlación matemática de Pearson entre dos vectores de retorno
    function calculatePearson(vX, vY) {
      if (!vX || !vY || vX.length !== vY.length || vX.length === 0) return 0.05;
      const n = vX.length;
      const meanX = vX.reduce((a, b) => a + b, 0) / n;
      const meanY = vY.reduce((a, b) => a + b, 0) / n;
      let num = 0, denX = 0, denY = 0;
      for (let i = 0; i < n; i++) {
        const dx = vX[i] - meanX;
        const dy = vY[i] - meanY;
        num += dx * dy;
        denX += dx * dx;
        denY += dy * dy;
      }
      if (denX === 0 || denY === 0) return 0.0;
      return num / (Math.sqrt(denX) * Math.sqrt(denY));
    }

