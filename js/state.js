function enrichBotPortfolioCategories(b) {
  if (!b) return b;
  const name = String(b.name || b.strategy || b.id || '').toUpperCase();
  const ea = String(b.ea_name || b.eaName || '').toUpperCase();
  const bid = String(b.id || '').toUpperCase();
  const params = b.params || {};
  
  let tpVal = 2.5;
  try {
    const tpStr = String(params.InpTP_R_Multiple || params.InpTP || '2.5');
    tpVal = parseFloat(tpStr.replace(/[^\d.]/g, '')) || 2.5;
  } catch(e) {
    tpVal = 2.5;
  }

  // Si ya tiene categorías explícitas válidas, las respetamos
  if (!b.macroCategory || b.macroCategory === 'SIN_ASIGNAR') {
    if (ea.includes('CoreSys') || name.includes('CoreSys') || bid.startsWith('STR')) {
      const trigger = String(params.InpEntryTriggerMode || '0');
      if (trigger === '1' || name.includes('PULLBACK') || name.includes('EMA')) {
        b.macroCategory = 'Convexo (Tendencia)';
        b.microCategory = b.microCategory || 'Trend Following';
      } else if (name.includes('ENTROPY') || name.includes('SHANNON')) {
        b.macroCategory = 'Híbrido / Especial';
        b.microCategory = b.microCategory || 'ML / IA';
      } else {
        b.macroCategory = 'Convexo (Tendencia)';
        b.microCategory = b.microCategory || 'Momentum';
      }
    } else if (ea.includes('ReversionSys') || ea.includes('REV') || name.includes('PO3') || name.includes('ReversionSys') || bid.startsWith('REV') || bid.startsWith('REV')) {
      b.macroCategory = 'Cóncavo (Reversión)';
      if (name.includes('DAILY') || name.includes('PDH') || name.includes('PDL') || name.includes('H1') || name.includes('H4')) {
        b.microCategory = b.microCategory || 'Smart Money';
      } else {
        b.microCategory = b.microCategory || 'Reversión';
      }
    } else if (ea.includes('MomentumSys') || name.includes('MomentumSys') || bid.startsWith('MOM') || bid.startsWith('JCK')) {
      if (name.includes('PRE-NY') || name.includes('PRE-MERCADO') || name.includes('MEDIA MAÑANA')) {
        b.macroCategory = 'Convexo (Tendencia)';
        b.microCategory = b.microCategory || 'Smart Money';
      } else if (name.includes('EXPANSIÓN') || name.includes('EXPANSION') || name.includes('TREND')) {
        b.macroCategory = 'Convexo (Tendencia)';
        b.microCategory = b.microCategory || 'Trend Following';
      } else if (name.includes('BE') || name.includes('BREAK-EVEN') || name.includes('DEFENSIVO')) {
        b.macroCategory = 'Híbrido / Especial';
        b.microCategory = b.microCategory || 'Grid / Scalping';
      } else {
        b.macroCategory = (tpVal >= 2.5) ? 'Convexo (Tendencia)' : 'Híbrido / Especial';
        b.microCategory = b.microCategory || 'Smart Money';
      }
    } else {
      if ((b.winRate || 50) > 55) {
        b.macroCategory = 'Cóncavo (Reversión)';
        b.microCategory = b.microCategory || 'Reversión';
      } else {
        b.macroCategory = 'Convexo (Tendencia)';
        b.microCategory = b.microCategory || 'Trend Following';
      }
    }
  }

  if (!b.microCategory) {
    b.microCategory = (b.macroCategory.includes('Convexo')) ? 'Momentum' : 'Smart Money';
  }

  return b;
}
